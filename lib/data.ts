/** 매장 정보의 영업시간 "HH:mm - HH:mm" → 분 단위 [여는 시각, 닫는 시각] */
export function parseOpenHours(openHours: string): [number, number] {
  const [open, close] = openHours.split("-").map((t) => {
    const [h, m] = t.trim().split(":").map(Number);
    return h * 60 + m;
  });
  return [open, close];
}
